def sum_negative_between_min_max(arr):
    """
    Находит сумму отрицательных элементов, расположенных между 
    максимальным и минимальным элементами массива.
    """
    if not arr:
        return 0
    
    # Находим индексы максимального и минимального элементов
    idx_max = 0
    idx_min = 0
    
    for i in range(1, len(arr)):
        if arr[i] > arr[idx_max]:
            idx_max = i
        if arr[i] < arr[idx_min]:
            idx_min = i
    
    # Определяем границы интервала
    start = min(idx_max, idx_min)
    end = max(idx_max, idx_min)
    
    # Суммируем отрицательные элементы между ними
    total = 0
    for i in range(start + 1, end):
        if arr[i] < 0:
            total += arr[i]
    
    return total


# Пример использования
if __name__ == "__main__":
    # Тестовые примеры
    test_cases = [
        [5, -2, 3, -4, 1, -6, 8],     # макс=8(индекс6), мин=-6(индекс5) -> между ними нет элементов
        [10, -5, 3, -2, 7, -8, 1],     # макс=10(0), мин=-8(5) -> между: -5, 3, -2, 7 -> сумма отрицательных = -7
        [-1, -2, -3, -4, -5],          # макс=-1(0), мин=-5(4) -> между: -2, -3, -4 -> сумма = -9
        [0, 0, 0, 0],                  # все равны -> между ними нет элементов
        [3, -1, 2, -4, 5, -6, 1],      # макс=5(4), мин=-6(5) -> между нет элементов
        [-10, 2, -3, 4, -5, 6, -7],    # макс=6(5), мин=-10(0) -> между: 2, -3, 4, -5, 6 -> сумма = -8
        [1, -2, 3, -4, 5]              # макс=5(4), мин=-4(3) -> между нет элементов
    ]
    
    for i, arr in enumerate(test_cases, 1):
        result = sum_negative_between_min_max(arr)
        print(f"Тест {i}: {arr} -> {result}")